type presetHistoryEntry struct {
	consolidated bool
	presets      map[string]groupPreset
}

func presetHistory() []presetHistoryEntry {
	return []presetHistoryEntry{
		{false, groupPresetsV1()},
		{false, groupPresetsV2()},
		{true, groupPresetsV3Dev()},
		{false, groupPresetsV3()},
		{true, groupPresetsV4()},
	}
}

func matchingHistoricalPreset(group permissionGroup) (presetHistoryEntry, groupPreset, bool) {
	for _, entry := range presetHistory() {
		legacy, ok := entry.presets[group.PresetID]
		if !ok || legacy.Version != group.PresetVersion || !reflect.DeepEqual(group.Policy, legacy.Policy) {
			continue
		}
		return entry, legacy, true
	}
	return presetHistoryEntry{}, groupPreset{}, false
}

func addPolicyWarning(warnings []string, value string) []string {
	if value == "" || slices.Contains(warnings, value) {
		return warnings
	}
	return append(warnings, value)
}

func mergePolicyWarnings(existing, added []string) []string {
	out := slices.Clone(existing)
	for _, warning := range added {
		out = addPolicyWarning(out, warning)
	}
	slices.Sort(out)
	return out
}

func translateLegacyPresetPolicy(legacy AgentPolicy) (AgentPolicy, []string) {
	out := EmptyAgentPolicy()
	out.HostMode = legacy.HostMode
	out.Hosts = slices.Clone(legacy.Hosts)
	warnings := []string{}
	consumed := map[string]bool{}

	allowsAll := func(ids ...string) bool {
		for _, id := range ids {
			if !legacy.AllowsOperation(id) {
				return false
			}
		}
		return true
	}
	translate := func(target string, sources ...string) {
		if !allowsAll(sources...) {
			return
		}
		out.Actions[target] = authorization.Grant{Effect: authorization.EffectAllow}
		for _, source := range sources {
			consumed[source] = true
		}
		warnings = addPolicyWarning(warnings, target)
	}

	// A merged current ID is safe only when every old semantic represented by
	// that ID was explicitly allowed by the exact historical template.
	translate("file.perm", "file.chmod", "file.chown", "file.chtimes")
	translate("file.link", "file.readlink", "file.symlink", "file.link")
	translate("file.fs", "file.realpath", "file.statvfs", "file.truncate")
	translate("forward.open", "forward.open.local", "forward.open.remote", "forward.open.dynamic")
	translate("ext.get", "ext.get", "ext.use", "ext.release")
	if allowsAll("file.write", "file.replace") {
		out.Actions["file.write"] = cloneGrant(legacy.Actions["file.write"])
		consumed["file.write"] = true
		consumed["file.replace"] = true
		warnings = addPolicyWarning(warnings, "file.write")
	}
	if allowsAll("profile.list", "profile.get") {
		out.Actions["profile.list"] = cloneGrant(legacy.Actions["profile.list"])
		consumed["profile.list"] = true
		consumed["profile.get"] = true
		warnings = addPolicyWarning(warnings, "profile.list")
	}

	for operation, grant := range legacy.Actions {
		if consumed[operation] {
			continue
		}
		if _, known := authorization.Lookup(operation); !known || legacyOperationSemanticsChanged[operation] {
			warnings = addPolicyWarning(warnings, operation)
			continue
		}
		out.Actions[operation] = cloneGrant(grant)
	}
	slices.Sort(warnings)
	return out, warnings
}

func upgradePresetGroups(s *managedState) bool {
	current := map[string]groupPreset{}
	for _, preset := range groupPresets() {
		current[preset.ID] = preset
	}
	changed := false
	for id, group := range s.Groups {
		preset, ok := current[group.PresetID]
		if !ok || group.ID != "preset-"+preset.ID || group.PresetVersion <= 0 || group.PresetVersion >= preset.Version {
			continue
		}
		historical, legacy, ok := matchingHistoricalPreset(group)
		if !ok {
			continue
		}
		var warnings []string
		if historical.consolidated {
			group.Policy = clonePolicy(legacy.Policy)
		} else {
			group.Policy, warnings = translateLegacyPresetPolicy(legacy.Policy)
		}
		if group.Description == legacy.Description {
			group.Description = preset.Description
		}
		group.PolicyVocabulary = permissionPolicyVocabularyVersion
		group.PolicyWarnings = mergePolicyWarnings(group.PolicyWarnings, warnings)
		group.PresetVersion = preset.Version
		group.Revision++
		s.Groups[id] = group
		changed = true
	}
	if changed {
		s.AccessRevision++
	}
	return changed
}

func seedPermissionGroups(s *managedState, now time.Time) {
	s.Groups = map[string]permissionGroup{}
	for _, preset := range groupPresets() {
		id := "preset-" + preset.ID
		s.Groups[id] = permissionGroup{ID: id, Name: preset.Name, Description: preset.Description, Enabled: true, Revision: 1, CreatedAt: now, Policy: clonePolicy(preset.Policy), PolicyVocabulary: permissionPolicyVocabularyVersion, PresetID: preset.ID, PresetVersion: preset.Version}
	}
	s.DefaultGroupID = "preset-no-access"
	s.AccessRevision = 1
}

func groupNameAvailable(s managedState, name, except string) bool {
	for id, g := range s.Groups {
		if id != except && strings.EqualFold(g.Name, name) {
			return false
		}
	}
	return true
}

func boundGroupID(s managedState, a agentRecord) string {
	if a.GroupID != "" {
		return a.GroupID
	}
	return s.DefaultGroupID
}
func resolvedAgentPolicy(s managedState, a agentRecord) (AgentPolicy, error) {
	if s.Version != managedStateVersion {
		return AgentPolicy{}, errors.New("unsupported permission state version")
	}
	id := boundGroupID(s, a)
	if id == deniedGroupID {
		return AgentPolicy{}, errors.New("principal has no active permission group")
	}
	group, ok := s.Groups[id]
	if !ok || !group.Enabled {
		return AgentPolicy{}, errors.New("permission group is missing or disabled")
	}
	return clonePolicy(group.Policy), nil
}
func stateAgentPolicy(s managedState, id string) AgentPolicy {
	a, ok := s.Agents[id]
	if !ok {
		return EmptyAgentPolicy()
	}
	p, err := resolvedAgentPolicy(s, a)
	if err != nil {
		return EmptyAgentPolicy()
	}
	return p
}

func cloneGroups(in map[string]permissionGroup) map[string]permissionGroup {
	out := maps.Clone(in)
	if out == nil {
		out = map[string]permissionGroup{}
	}
	return out
}
func validateGroupState(s managedState) error {
	if len(s.Groups) > maxPermissionGroups || s.AccessRevision == 0 {
		return errors.New("invalid permission group state")
	}
	if _, ok := s.Groups[s.DefaultGroupID]; !ok {
		return errors.New("default permission group is missing")
	}
	names := map[string]bool{}
	for id, g := range s.Groups {
		if id == "" || id == deniedGroupID || id != g.ID || !validLabel(g.Name) || g.Revision == 0 || g.CreatedAt.IsZero() || len(g.Description) > 2048 || g.PolicyVocabulary > permissionPolicyVocabularyVersion {
			return errors.New("invalid permission group")
		}
		name := strings.ToLower(g.Name)
		if names[name] {
			return errors.New("duplicate permission group name")
		}
		names[name] = true
		if err := validateAgentPolicy(g.Policy); err != nil {
			return fmt.Errorf("group %s: %w", id, err)
		}
	}
	for _, a := range s.Agents {
		id := boundGroupID(s, a)
		if id == deniedGroupID {
			continue
		}
		if _, ok := s.Groups[id]; !ok {
			return errors.New("principal references a missing permission group")
		}
	}
	return nil
}

func groupMemberIDs(s managedState, groupID string) []string {
	ids := []string{}
	for id, a := range s.Agents {
		if boundGroupID(s, a) == groupID {
			ids = append(ids, id)
		}
	}
	sort.Strings(ids)
	return ids
}

func (m *Managed) cancelPrincipalsLocked(ids []string) {
	wanted := map[string]bool{}
	for _, id := range ids {
		wanted[id] = true
	}
	for _, grant := range m.state.OAuthGrants {
		if !wanted[grant.AgentID] {
			continue
		}
		for _, record := range m.state.OAuthAccess {
			if record.GrantID == grant.ID {
				m.cancelCredentialLocked(record.ID)
			}
		}
	}
	for id, token := range m.state.Tokens {
		if wanted[token.PrincipalID] {
			m.cancelCredentialLocked(id)
		}
	}
}

// cancelBackgroundForPrincipalsLocked stops detached work whose authority may
// have changed with a policy or group binding. It deliberately does not cancel
// request contexts or MCP transports: those carry the authenticated identity
// and must stay alive so the next business operation resolves the new policy.
func (m *Managed) cancelBackgroundForPrincipalsLocked(ids []string) {
	wanted := map[string]bool{}
	for _, id := range ids {
		wanted[id] = true
	}
	for id, token := range m.state.Tokens {
		if !wanted[token.PrincipalID] {
			continue
		}
		for _, work := range m.background[id] {
			if !m.backgroundWorkAuthorizedLocked(id, work.authority) {
				work.cancel()
			}
		}
	}
	for _, record := range m.state.OAuthAccess {
		grant := m.state.OAuthGrants[record.GrantID]
		if !wanted[grant.AgentID] {
			continue
		}
		for _, work := range m.background[record.ID] {
			if !m.backgroundWorkAuthorizedLocked(record.ID, work.authority) {
				work.cancel()
			}
		}
	}
}

func (m *Managed) backgroundWorkAuthorizedLocked(credentialID string, authority BackgroundWorkAuthority) bool {
	if len(authority.Operations) == 0 && len(authority.Hosts) == 0 {
		return false
	}
	principalID := ""
	if token, ok := m.state.Tokens[credentialID]; ok {
		principalID = token.PrincipalID
	} else {
		for _, record := range m.state.OAuthAccess {
			if record.ID == credentialID {
				principalID = m.state.OAuthGrants[record.GrantID].AgentID
				break
			}
		}
	}
	agent, ok := m.state.Agents[principalID]
	if !ok || !agent.Enabled {
		return false
	}
	policy, err := resolvedAgentPolicy(m.state, agent)
	if err != nil {
		return false
	}
	for _, operation := range authority.Operations {
		if !policy.MayRequestOperation(operation) {
			return false
		}
	}
	for _, host := range authority.Hosts {
		if !policy.AllowsHost(host) {
			return false
		}
	}
	return true
}
